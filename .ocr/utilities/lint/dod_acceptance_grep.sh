#!/usr/bin/env bash
# DoD acceptance grep for the B0 manifest-render effort (step (d)/(f)).
# Operator bar: "every single atomic value is declarative" -> the atomic literal
# VALUES (uid seed + derived owners, hardcode markers) live ONLY in
# manifests/ + the filter plugin. Hand-authored source (ansible/ scripts/ config/)
# must be ZERO-hit. Generated artifacts are excluded MECHANICALLY by their
# first-line banner (NOT a filename list) so the exclusion itself introduces no
# hardcoding.
#
# Usage: dod_acceptance_grep.sh [RENDERED_DIR]
#   Part 1 (always): source-tree literal scan.
#   Part 2 (if RENDERED_DIR given): rendered-unit lme_certs/ca.key + User= scan
#     over an all-profile render (each profile in a subdir).
set -uo pipefail
REPO="/home/tristan/gitters/LME"
cd "$REPO" || exit 2
RENDERED_DIR="${1:-}"
FAIL=0

# --- allow-list (literals legitimately live here) ---------------------------
#   manifests/**               : single source of truth
#   filter_plugins/lme_manifests.py : the derivation arithmetic + doc comments
#   ansible/templates/units/*.j2    : pure renderers (reference manifest vars)
# A file is ALSO excluded if its FIRST line is the canonical generated banner.
GEN_BANNER='^#[{ ]*GENERATED by Ansible .* DO NOT hand-edit'
is_excluded() {
  case "$1" in
    manifests/*) return 0 ;;
    ansible/roles/podman/filter_plugins/lme_manifests.py) return 0 ;;
    ansible/templates/units/*.j2) return 0 ;;
  esac
  # mechanical generated-artifact test: first line carries the banner
  head -n1 "$1" 2>/dev/null | grep -qE "$GEN_BANNER" && return 0
  return 1
}

# scan set = hand-authored source under ansible/ scripts/ config/
mapfile -t SRC < <(find ansible scripts config -type f \
  \( -name '*.yml' -o -name '*.yaml' -o -name '*.sh' -o -name '*.j2' -o -name '*.py' \) 2>/dev/null | sort)

scan() { # $1=label  $2=ERE
  local label="$1" ere="$2" hits=0 f
  echo "--- CHECK: $label"
  for f in "${SRC[@]}"; do
    is_excluded "$f" && continue
    while IFS= read -r line; do
      echo "   HIT $f:$line"; hits=$((hits+1))
    done < <(grep -nE "$ere" "$f" 2>/dev/null)
  done
  if [ "$hits" -eq 0 ]; then echo "   OK (0 hits)"; else echo "   FAIL ($hits hits)"; FAIL=1; fi
}

echo "===================================================================="
echo "PART 1 -- source-tree literal scan (ansible/ scripts/ config/)"
echo "excluded: manifests/, filter plugin, units/*.j2, first-line GENERATED banner"
echo "===================================================================="
# 1. hardcode-corruption markers (live only in the static quadlet/ dir -> G4 deletes)
scan "no HARDCODED corruption markers" '#@@?TODO:OPERATOR:[[:space:]]*HARDCODED'
# 2. uid SEED constants (subuid_base / slot_size) belong ONLY in global.yml + plugin
scan "no subuid_base/slot_size seed literals in source" '\b(165536|3048)\b'
# 3. DERIVED owner/base uids are computed, never written -> must appear nowhere in source
scan "no derived userns/owner uids in source" '\b(166536|168584|169584|171632|174680|177728)\b'

if [ -n "$RENDERED_DIR" ] && [ -d "$RENDERED_DIR" ]; then
  echo ""
  echo "===================================================================="
  echo "PART 2 -- rendered-unit scan over $RENDERED_DIR"
  echo "===================================================================="
  # sanctioned lme_certs consumers: ES workspace + the two generator oneshots
  SANCTIONED='lme-elasticsearch|lme-setup-certs|lme-setup-accts'
  echo "--- CHECK: only sanctioned rendered units mount lme_certs / reference ca.key"
  bad=0
  while IFS= read -r hit; do
    file="${hit%%:*}"; base="$(basename "$file")"
    if echo "$base" | grep -qE "$SANCTIONED"; then continue; fi
    echo "   HIT $hit"; bad=$((bad+1))
  done < <(grep -rnE 'lme_certs|ca\.key|ca/ca\.key' "$RENDERED_DIR" 2>/dev/null | grep -E 'Volume=|/certs')
  if [ "$bad" -eq 0 ]; then echo "   OK (0 unsanctioned)"; else echo "   FAIL ($bad)"; FAIL=1; fi

  echo "--- INFO: every rendered User= directive (must be DECLARED in a manifest run_as + justified)"
  grep -rnE '^User=' "$RENDERED_DIR" 2>/dev/null | sed 's/^/   /' || echo "   (none)"
  echo "   ^ cross-check each against a manifest run_as.user (filebeat=journal; setup-certs/accts=generator)."
fi

echo ""
if [ "$FAIL" -eq 0 ]; then echo "ACCEPTANCE: PASS (all source checks zero-hit)"; else echo "ACCEPTANCE: FAIL (see HITs above)"; fi
exit "$FAIL"
